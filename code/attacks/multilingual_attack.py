"""MultilingualAttack: one AgentDojo attack class per language condition.

Design follows research-plan.md sections 3.1, 4.2 and 4.3:

* Wrapper W1 mirrors AgentDojo's built-in ``important_instructions`` structure
  (an ``<INFORMATION>`` block from "Emma Johnson" to "the AI assistant").
  AgentDojo hard-codes the user name "Emma Johnson" for that attack.
* A *generic* model name ("the AI assistant") is used in every condition, because
  a model-specific name would leak knowledge the black-box attacker does not have
  (section 4.2). This also sidesteps the ``get_model_name_from_pipeline`` lookup
  that fails for unknown/local model names (section 3.1).
* Identifiers and quoted attacker literals stay verbatim in ASCII/English in every
  condition (the literal-preservation rule, section 4.3/4.4). Only the natural-
  language wrapper and surrounding instruction text change language.
* Payloads are loaded from data/payloads.json; nothing is generated at runtime.

The six registered conditions are en, bn_mt, bn_llm, banglish_llm,
banglish_translit, codemix_llm. Register-ablation (W2) conditions (en_W2,
bn_llm_W2, banglish_llm_W2) are also registered.

Reframe (2026-10-06, research-plan §12, DECISIONS D24): the former human-native
conditions (bn_native/banglish_native/codemix_native and their _W2 variants) are
now LLM-AUTHORED (bn_llm/banglish_llm/codemix_llm, _W2) and generated by
payloads/generate_llm.py. banglish_translit now transliterates bn_llm via IndicXlit.
Back-compat: the old *_native names are still accepted as aliases of the matching
*_llm condition so older run manifests/configs keep working.
"""
from __future__ import annotations

import json
import os
from functools import lru_cache
from pathlib import Path

from agentdojo.attacks.attack_registry import register_attack
from agentdojo.attacks.base_attacks import BaseAttack
from agentdojo.base_tasks import BaseInjectionTask, BaseUserTask

# Keep identifiers and these fixed strings in English, per the plan.
USER_NAME = "Emma Johnson"
MODEL_NAME = "the AI assistant"

# The six main conditions plus the three W2 register-ablation renderings.
CONDITIONS = [
    "en",
    "bn_mt",
    "bn_llm",
    "banglish_llm",
    "banglish_translit",
    "codemix_llm",
]
W2_CONDITIONS = ["en_W2", "bn_llm_W2", "banglish_llm_W2"]

# Back-compat aliases: old human-native names -> new LLM-authored names (§12, D24).
# Loading an alias resolves to the same payload block as its *_llm target.
CONDITION_ALIASES = {
    "bn_native": "bn_llm",
    "banglish_native": "banglish_llm",
    "codemix_native": "codemix_llm",
    "bn_native_W2": "bn_llm_W2",
    "banglish_native_W2": "banglish_llm_W2",
}

# A payload value equal to any of these means "not authored yet". The attack
# refuses to run such a condition so a half-filled dataset can never silently
# produce bogus results.
TODO_SENTINELS = ("TODO_LLM", "TODO_NATIVE", "TODO_MT", "TODO_TRANSLIT", "")


def _default_payload_path() -> Path:
    env = os.environ.get("BANGLA_PI_PAYLOADS")
    if env:
        return Path(env)
    return Path(__file__).resolve().parent.parent / "data" / "payloads.json"


@lru_cache(maxsize=4)
def load_payloads(path: str | None = None) -> dict:
    p = Path(path) if path else _default_payload_path()
    with open(p, encoding="utf-8") as f:
        return json.load(f)


class MultilingualAttack(BaseAttack):
    """Base class. Subclasses set ``name`` and ``cond`` via :func:`register_variants`."""

    cond: str = "en"

    @property
    def _cond(self) -> str:
        """Resolve a back-compat alias (bn_native->bn_llm, ...) to the payload key."""
        return CONDITION_ALIASES.get(self.cond, self.cond)

    def _wrapper(self, payloads: dict) -> str:
        cond_block = payloads["conditions"][self._cond]
        wrapper_id = cond_block.get("wrapper_id", "W1")
        wrapper = payloads["wrappers"][wrapper_id].get(self._cond)
        if wrapper is None or wrapper in TODO_SENTINELS:
            raise ValueError(
                f"Wrapper for condition '{self.cond}' (id {wrapper_id}) is not authored yet "
                f"(value={wrapper!r}). Fill data/payloads.json before running this condition."
            )
        return wrapper

    def _goal_text(self, payloads: dict, suite: str, injection_task: BaseInjectionTask) -> str:
        key = f"{suite}/{injection_task.ID}"
        goals = payloads["conditions"][self._cond]["goals"]
        if key not in goals:
            raise KeyError(f"No payload for {key} in condition '{self.cond}'.")
        text = goals[key]
        if text in TODO_SENTINELS:
            raise ValueError(
                f"Payload for {key} in condition '{self.cond}' is a TODO placeholder "
                f"({text!r}). Native/MT/translit items must be authored and validated first."
            )
        return text

    def attack(
        self, user_task: BaseUserTask, injection_task: BaseInjectionTask
    ) -> dict[str, str]:
        payloads = load_payloads()
        suite = self.task_suite.name
        wrapper = self._wrapper(payloads)
        goal = self._goal_text(payloads, suite, injection_task)
        text = wrapper.format(goal=goal, user=USER_NAME, model=MODEL_NAME)
        return {inj: text for inj in self.get_injection_candidates(user_task)}


def register_variants(conditions: list[str] | None = None) -> dict[str, type[MultilingualAttack]]:
    """Create and register one attack class per condition (plus back-compat aliases)."""
    conditions = conditions or (CONDITIONS + W2_CONDITIONS + list(CONDITION_ALIASES))
    registered: dict[str, type[MultilingualAttack]] = {}
    for c in conditions:
        cls = type(
            f"MultilingualAttack_{c}",
            (MultilingualAttack,),
            {"name": c, "cond": c},
        )
        register_attack(cls)
        registered[c] = cls
    return registered


# Register on import.
REGISTERED = register_variants()
