def build_notebook(model_key, blob, info, est, subset="150", shard=1, n_shards=1) -> dict:
    mk = model_key or "gemma"
    e = est["models"][mk]["est_session_h"]
    est_h = round(e / n_shards if n_shards > 1 else e, 2)
    cells = [
        header_md(model_key, info, est, shard, n_shards),
        code(unpack_cell(blob, info), "unpack"),
        code(params_cell(mk, subset, shard, n_shards, est_h), "params"),
        code(GPU_CELL, "gpu"),
        code(INSTALL_CELL, "gpu"),
        code(DOWNLOAD_CELL, "gpu"),
        code(SERVE_CELL, "gpu"),
        code(RUN_CELL, "run"),
        code(FINAL_CELL, "finalize"),
        md("""## After the run (on the box)
Download the Output (or `<run_id>_traces.zip` + `runs/<run_id>.jsonl` + `runs_manifest_<run_id>.json`), check the
`MAIN_RESULT` line and that `embed_sha256` matches the notebook header, then analyse with
`python -m analysis.run_analysis` (see `analysis/README.md`). Judge pass: `kaggle/JUDGE_ON_KAGGLE.md`.
Record slug/version, wall time, `MAIN_RESULT`, model id and GGUF sha256 in `DECISIONS.md`."""),
    ]
    return {"cells": cells,
            "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                         "language_info": {"name": "python"}},
            "nbformat": 4, "nbformat_minor": 5}


def nb_filename(model_key, shard=1, n_shards=1) -> str:
    if model_key is None:
        return "main_grid.ipynb"
    base = NB_NAME[model_key]
    return f"{base}_shard{shard}of{n_shards}.ipynb" if n_shards > 1 else f"{base}.ipynb"


def write_notebooks(model_keys, out_dir: Path = KAGGLE, subset="150", shards=None,
                    generic=False) -> list[dict]:
    blob, info = build_tarball()
    est = estimates(subset)
    written = []
    jobs = []
    for k in model_keys:
        n = shards or est["models"][k]["shards"]
        jobs += [(k, s, n) for s in range(1, n + 1)]
    if generic:
        jobs.append((None, 1, 1))
    for k, s, n in jobs:
        nb = build_notebook(k, blob, info, est, subset, s, n)
        txt = json.dumps(nb, ensure_ascii=False, indent=1) + "\n"
        size = len(txt.encode("utf-8"))
        if size > KAGGLE_LIMIT_BYTES:
            raise SystemExit(f"{nb_filename(k, s, n)} is {size} B > {KAGGLE_LIMIT_BYTES} (Kaggle 1 MB limit)")
        path = out_dir / nb_filename(k, s, n)
        path.write_text(txt, encoding="utf-8")
        written.append({"path": str(path), "bytes": size, "model": k, "shard": f"{s}/{n}"})
    return written, info, est


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--model", default="all", help="gemma|ministral|granite|qwen|gptoss (or long label) or all")
    ap.add_argument("--subset", default="150", choices=sorted(SUBSET_PAIRS))
    ap.add_argument("--shards", type=int, default=None, help="force N shard notebooks (default: auto, >11 h)")
    ap.add_argument("--estimates", action="store_true", help="print hour estimates and exit")
    ap.add_argument("--out-dir", default=str(KAGGLE))
    a = ap.parse_args(argv)
    est = estimates(a.subset)
    if a.estimates:
        print(json.dumps(est, indent=1))
        return 0
    keys = LAUNCH_ORDER if a.model == "all" else [resolve_model(a.model)]
    written, info, est = write_notebooks(keys, Path(a.out_dir), a.subset, a.shards, generic=(a.model == "all"))
    print(f"embedded tarball: {info['bytes']} B gz ({info['raw_tar_bytes']} B tar), {info['n_files']} files, "
          f"sha256 {info['sha256']}")
    for w in written:
        mk = w["model"]
        e = est["models"][mk]["est_session_h"] if mk else None
        print(f"wrote {w['path']} ({w['bytes']} B) shard {w['shard']}" + (f"  est {e} h" if e else "  (generic)"))
    print(f"total estimate {est['total_est_h']} h for {est['episodes_per_model']} episodes/model")
    return 0


