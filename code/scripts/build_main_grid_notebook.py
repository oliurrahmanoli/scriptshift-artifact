def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def embed_file_list(root: Path = ROOT) -> list[str]:
    """CODE_FILES + every file named in PAYLOAD_SHA256SUMS.txt (relative to data/conditions)."""
    files = set(CODE_FILES)
    sums = (root / "data" / "conditions" / "PAYLOAD_SHA256SUMS.txt").read_text(encoding="utf-8")
    for line in sums.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        _, name = line.split("  ", 1)
        if not name.startswith("CANONICAL_GOALS_JSON("):
            files.add(f"data/conditions/{name}")
    out = sorted(files)
    for rel in out:
        p = root / rel
        if _FORBIDDEN.search(rel):
            raise ValueError(f"refusing to embed {rel} (tests/traces/backups/logs/notebooks excluded)")
        if not p.is_file():
            raise FileNotFoundError(rel)
        if p.stat().st_size > MAX_EMBED_FILE_BYTES:
            raise ValueError(f"refusing to embed big file {rel} ({p.stat().st_size} B)")
    return out


def build_tarball(root: Path = ROOT, files: list[str] | None = None) -> tuple[bytes, dict]:
    """Deterministic tar.gz: sorted entries, mtime 0, uid/gid 0, mode 0644, gzip mtime 0."""
    files = files or embed_file_list(root)
    manifest = {"files": {}, "n_files": len(files),
                "note": "generated by scripts/build_main_grid_notebook.py; sha256 of each embedded file"}
    blobs = {}
    for rel in files:
        b = (root / rel).read_bytes()
        blobs[rel] = b
        manifest["files"][rel] = {"sha256": sha256_bytes(b), "bytes": len(b)}
    blobs["EMBED_MANIFEST.json"] = (json.dumps(manifest, indent=1, sort_keys=True) + "\n").encode()
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.USTAR_FORMAT) as tf:
        for rel in sorted(blobs):
            ti = tarfile.TarInfo(rel)
            ti.size, ti.mtime, ti.mode = len(blobs[rel]), 0, 0o644
            ti.uid = ti.gid = 0
            ti.uname = ti.gname = ""
            tf.addfile(ti, io.BytesIO(blobs[rel]))
    gz = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=gz, mtime=0, compresslevel=9) as g:
        g.write(raw.getvalue())
    blob = gz.getvalue()
    info = {"sha256": sha256_bytes(blob), "bytes": len(blob), "raw_tar_bytes": len(raw.getvalue()),
            "n_files": len(files) + 1, "manifest_sha256": sha256_bytes(blobs["EMBED_MANIFEST.json"]),
            "files": files}
    return blob, info


# ----------------------------------------------------------------------------- estimates
def estimates(subset: str = "150", conditions=FAST_CONDITIONS, utility: bool = True) -> dict:
    n_pairs = len(json.loads((ROOT / SUBSET_PAIRS[subset]).read_text(encoding="utf-8"))["pairs"])
    n_eps = episode_count(n_pairs, len(conditions), utility)
    out = {"n_pairs": n_pairs, "n_conditions": len(conditions), "utility_episodes":
           sum(UTILITY_TASKS_V122.values()) if utility else 0, "episodes_per_model": n_eps,
           "overhead": LOAD_OVERHEAD, "setup_h": SETUP_H, "max_session_h": MAX_SESSION_H, "models": {}}
    for k in LAUNCH_ORDER:
        r = MODELS[k]["pilot_eps_h"]
        h = estimate_hours(n_eps, r)
        out["models"][k] = {"pilot_eps_h": r, "episode_h": round(n_eps / r, 2),
                            "est_session_h": round(h, 2), "shards": shards_needed(h),
                            "est_session_h_at_half_rate": round(estimate_hours(n_eps, r / 2), 2)}
    out["total_est_h"] = round(sum(v["est_session_h"] for v in out["models"].values()), 2)
    return out


