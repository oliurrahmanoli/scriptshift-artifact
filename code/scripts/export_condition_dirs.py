"""Export data/payloads.json into data/conditions/<cond>/ for human authoring.

Canonical runtime source remains payloads.json. Re-run after editing payloads.
See data/conditions/README.md.
"""
from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAYLOADS_PATH = ROOT / "data" / "payloads.json"
GOALS_PATH = ROOT / "data" / "goals_en.json"
DRAFTS_PATH = ROOT / "data" / "drafts_for_native_review.json"
OUT = ROOT / "data" / "conditions"

TODO = {"TODO_LLM", "TODO_NATIVE", "TODO_MT", "TODO_TRANSLIT", ""}
MAIN = ["en", "bn_mt", "bn_llm", "banglish_llm", "banglish_translit", "codemix_llm"]
W2 = ["en_W2", "bn_llm_W2", "banglish_llm_W2"]
ALL = MAIN + W2


def en_header(goal_en: str) -> str:
    """The English goal as comment lines. EVERY physical line is '#'-prefixed so a
    multi-line goal (workspace/injection_task_9, _12, _13) cannot leak into the body that
    import_condition_dirs.py reads back (D26; the old single '# EN:' line left the goal's
    continuation lines uncommented)."""
    lines = goal_en.split("\n")
    return "\n".join([f"# EN: {lines[0]}"] + [f"#     {ln}".rstrip() for ln in lines[1:]])


def main() -> None:
    payloads = json.loads(PAYLOADS_PATH.read_text(encoding="utf-8"))
    goals = json.loads(GOALS_PATH.read_text(encoding="utf-8"))
    drafts = {}
    if DRAFTS_PATH.exists():
        drafts = json.loads(DRAFTS_PATH.read_text(encoding="utf-8")).get("items", {})

    OUT.mkdir(parents=True, exist_ok=True)
    wdir = OUT / "_wrappers"
    wdir.mkdir(exist_ok=True)
    for old in wdir.glob("*"):
        if old.is_file():
            old.unlink()

    for wid, block in payloads["wrappers"].items():
        for cond, text in block.items():
            if text is None:
                continue
            is_todo = isinstance(text, str) and text in TODO
            fname = wdir / f"{wid}__{cond}.txt"
            header = (
                f"# Wrapper {wid} for condition={cond}\n"
                f"# Placeholders: {{goal}}, {{user}}, {{model}}\n"
            )
            if is_todo:
                header += (
                    f"# STATUS: {text}\n"
                    f"# The authors must author native wrappers (research-plan.md §4.3, §4.10).\n"
                    f"# Do NOT paste AI-generated Bangla here as final.\n\n"
                )
                body = text + "\n"
            else:
                header += "# STATUS: filled\n\n"
                body = text if str(text).endswith("\n") else str(text) + "\n"
            fname.write_text(header + body, encoding="utf-8")

    rows = []
    for cond in ALL:
        cdir = OUT / cond
        cdir.mkdir(exist_ok=True)
        for old in cdir.glob("*.txt"):
            old.unlink()
        info = payloads["conditions"][cond]
        goalmap = info["goals"]
        filled = 0
        todos: dict[str, int] = {}
        for key in goals["order"]:
            gmeta = goals["goals"][key]
            val = goalmap[key]
            is_todo = isinstance(val, str) and (val in TODO or val.startswith("TODO_"))
            safe = key.replace("/", "__")
            if is_todo:
                todos[val] = todos.get(val, 0) + 1
                path = cdir / f"{safe}.{val}.txt"
                lines = [
                    f"# condition: {cond}",
                    f"# key: {key}",
                    f"# suite: {gmeta.get('suite', key.split('/')[0])}",
                    f"# scoring_group: {gmeta.get('scoring_group', '?')}",
                    f"# STATUS: {val}",
                    "# English goal (rewrite FROM THIS for native; do not copy MT drafts):",
                    en_header(gmeta['goal_en']),
                    "#",
                    "# Literal-preservation: keep emails, IBANs, URLs, file IDs, amounts,",
                    "# dates, and quoted attacker free-text EXACT ASCII English.",
                    "#",
                ]
                if cond in (
                    "bn_llm",
                    "banglish_llm",
                    "codemix_llm",
                    "bn_llm_W2",
                    "banglish_llm_W2",
                ):
                    lines.append("# OWNER: generated by payloads/generate_llm.py (Gemma/Qwen) on Kaggle (§12, D24).")
                    lines.append("# Reframe 2026-10-06: LLM-authored, NOT human-native. Validators: literal+script+back-translation.")
                    lines += ["#", "# === generate_llm.py fills this (replace sentinel) ===", val, ""]
                elif cond == "banglish_translit":
                    lines += [
                        "# Filled by scripts/make_translit.py = IndicXlit of bn_llm (§12, D24).",
                        "#",
                        val,
                        "",
                    ]
                else:
                    lines += [val, ""]
                path.write_text("\n".join(lines), encoding="utf-8")
            else:
                filled += 1
                path = cdir / f"{safe}.txt"
                path.write_text(
                    f"# condition: {cond}\n# key: {key}\n# STATUS: filled\n"
                    f"{en_header(gmeta['goal_en'])}\n\n{val}\n",
                    encoding="utf-8",
                )
        rows.append((cond, info["wrapper_id"], filled, len(goals["order"]), todos))

    readme = """# Attack condition directories (authoring scaffold)

Canonical runtime source of truth remains `../payloads.json` (loaded by
`attacks/multilingual_attack.py`). These directories mirror that file for
human authoring and review.

## Conditions (§4.3 / §11)

| Dir | Meaning | Who fills |
|---|---|---|
| `en` | English W1 (AgentDojo verbatim) | filled |
| `bn_mt` | Machine-translated Bangla (NLLB-200-3.3B) | `make_bn_mt_nllb.ipynb` |
| `bn_llm` | **LLM-authored** idiomatic Bangla | `generate_llm.py` (Gemma) |
| `banglish_llm` | **LLM-authored** romanised Banglish | `generate_llm.py` (Gemma) |
| `banglish_translit` | IndicXlit of `bn_llm` | scripts after `bn_llm` |
| `codemix_llm` | **LLM-authored** code-mix | `generate_llm.py` (Gemma) |
| `en_W2` / `bn_llm_W2` / `banglish_llm_W2` | Register ablation | en filled; `_llm` by generator |

Wrappers: `_wrappers/`. `TODO_*` sentinels must not run (attack class refuses).

Regenerate: `python scripts/export_condition_dirs.py`
Import: `python scripts/import_condition_dirs.py`
"""
    (OUT / "README.md").write_text(readme, encoding="utf-8")

    lines = [
        "# Payload scaffold status",
        "",
        f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')} Australia/Sydney.",
        f"Source: `data/payloads.json` · goals: **{len(goals['order'])}** / 35 injection tasks.",
        "",
        "| Condition | Wrapper | Filled | Total | TODO counts |",
        "|---|---|---:|---:|---|",
    ]
    for cond, wid, filled, total, todos in rows:
        t = ", ".join(f"{k}×{v}" for k, v in sorted(todos.items())) or "—"
        lines.append(f"| `{cond}` | {wid} | {filled} | {total} | {t} |")
    llm_slots = sum(v for *_, todos in rows for k, v in todos.items() if "LLM" in k)
    lines += [
        "",
        "## Summary vs 35 injection goals",
        "",
        f"- `en` + `en_W2`: filled.",
        f"- `bn_mt`: **{rows[1][2]}/35** (NLLB-200-3.3B via make_bn_mt_nllb.ipynb).",
        f"- LLM-authored `TODO_LLM` goal cells: **{llm_slots}** + wrappers (generate_llm.py on Kaggle).",
        f"- `banglish_translit`: blocked on `bn_llm`.",
        f"- Frozen fast-track sets (D26): see `PAYLOAD_SHA256SUMS.txt`, `_provenance/` and `_gen_meta.json`"
        f" in each LLM condition dir; DECISIONS.md D26 lists every fix and every item left TODO.",
        "",
    ]
    (OUT / "STATUS.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
